"""Fetch a reproducible, descriptive Snapshot governance corpus.

The output is intentionally metadata-only.  Keyword hits are candidate records,
not vulnerability labels and not evidence of a security failure.
"""
import argparse
import hashlib
import json
import urllib.request
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path


QUERY = """
query {
  proposals(first: 1000, where: {space_in: [\"uniswapgovernance.eth\"], created_gte: 1609459200}, orderBy: \"created\", orderDirection: asc) {
    id title body state created start end author choices scores scores_total space { id name }
  }
}
""".strip()

KEYWORDS = (
    "cross-chain", "cross chain", "bridge", "message", "arbitrum", "optimism",
    "base", "polygon", "celo", "layer 2", "l2", "rollup", "multichain",
)


def fetch(url: str) -> dict:
    payload = json.dumps({"query": QUERY}).encode("utf-8")
    request = urllib.request.Request(
        url,
        data=payload,
        headers={"Content-Type": "application/json", "User-Agent": "BTG-repro/1.0"},
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.loads(response.read().decode("utf-8"))


def text_of(proposal: dict) -> str:
    return " ".join(str(proposal.get(k) or "") for k in ("title", "body")).lower()


def year_of(timestamp: int) -> str:
    return datetime.fromtimestamp(int(timestamp), tz=timezone.utc).strftime("%Y")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parent / "results" / "public_governance")
    parser.add_argument("--endpoint", default="https://hub.snapshot.org/graphql")
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    response = fetch(args.endpoint)
    if response.get("errors"):
        raise RuntimeError(response["errors"])
    proposals = response.get("data", {}).get("proposals", [])
    if not proposals:
        raise RuntimeError("Snapshot returned no proposals")
    candidates = [
        p for p in proposals
        if any(keyword in text_of(p) for keyword in KEYWORDS)
    ]
    by_year = defaultdict(lambda: {"proposals": 0, "keyword_candidates": 0})
    for proposal in proposals:
        year = year_of(proposal["created"])
        by_year[year]["proposals"] += 1
    for proposal in candidates:
        by_year[year_of(proposal["created"])] ["keyword_candidates"] += 1
    state_counts = Counter(str(p.get("state") or "unknown") for p in proposals)
    candidate_state_counts = Counter(str(p.get("state") or "unknown") for p in candidates)
    raw = json.dumps(response, sort_keys=True, separators=(",", ":")).encode("utf-8")
    metadata = {
        "source": args.endpoint,
        "space": "uniswapgovernance.eth",
        "created_gte": 1609459200,
        "retrieved_at_utc": datetime.now(timezone.utc).isoformat(),
        "query_sha256": hashlib.sha256(QUERY.encode("utf-8")).hexdigest(),
        "raw_response_sha256": hashlib.sha256(raw).hexdigest(),
        "proposal_count": len(proposals),
        "keyword_candidate_count": len(candidates),
        "keyword_rule": "case-insensitive substring match over title and body",
        "keywords": list(KEYWORDS),
        "evidence_role": "Candidate records provide a provenance-indexed entry point for transaction-level evidence binding.",
    }
    (args.out / "raw_response.json").write_bytes(raw + b"\n")
    (args.out / "proposals.json").write_text(json.dumps(proposals, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (args.out / "keyword_candidates.json").write_text(json.dumps(candidates, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (args.out / "metadata.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    summary = {
        "proposal_count": len(proposals),
        "keyword_candidate_count": len(candidates),
        "state_counts": dict(sorted(state_counts.items())),
        "candidate_state_counts": dict(sorted(candidate_state_counts.items())),
        "by_year": dict(sorted(by_year.items())),
    }
    (args.out / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    rows = ["% Generated by experiments/fetch_public_governance.py.", r"\begin{table}[t]", r"\centering\small", r"\caption{Descriptive public-governance corpus retrieved from Snapshot. Keyword candidates are retained for evidence binding.}", r"\label{tab:public-corpus}", r"\begin{tabular}{@{}lrr@{}}\toprule", r"Year & Proposals & Keyword candidates \\ \midrule"]
    for year, values in sorted(by_year.items()):
        rows.append(f"{year} & {values['proposals']} & {values['keyword_candidates']} \\\\")
    rows += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (args.out / "table.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(json.dumps({"proposals": len(proposals), "keyword_candidates": len(candidates), "by_year": by_year}, default=dict))


if __name__ == "__main__":
    main()
