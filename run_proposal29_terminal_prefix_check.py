"""Compare a terminal-only projection with BTG on the same real Proposal 29 prefix."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUT = ROOT / "experiments" / "results" / "real_replay" / "additional_crosschain_cases.json"
OUTPUT = ROOT / "experiments" / "results" / "tool_comparison" / "proposal29_terminal_prefix_check.json"
TABLE = ROOT / "experiments" / "results" / "proposal29_terminal_prefix_table.tex"
PASS, VIOLATION, UNKNOWN = "PASS", "VIOLATION", "UNKNOWN"


def digest(value: object) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def same(left: object, right: object) -> bool:
    return isinstance(left, str) and isinstance(right, str) and left.lower() == right.lower()


def main() -> None:
    payload = json.loads(INPUT.read_text(encoding="utf-8"))
    case = next(item for item in payload["cases"] if item["proposal_id"] == 29)
    expected_before = case["steps"][1]["evidence"]["expected_before"]
    expected_after = case["steps"][2]["evidence"]["expected_after"]
    # The three rows are one ordered real-history prefix: L1 dispatch, the
    # destination state immediately before repair, and the committed repair.
    steps = case["steps"][:3]
    dispatch = steps[0]["evidence"]
    pre = steps[1]["evidence"]
    post = steps[2]["evidence"]
    btg = [
        PASS if dispatch.get("status") == 1 and dispatch.get("transaction_hash") == case["execution_tx"] else UNKNOWN,
        VIOLATION if pre.get("status") == "complete" and same(pre.get("before"), expected_before) else UNKNOWN,
        PASS if post.get("status") == "complete" and same(post.get("after"), expected_after) and post.get("changed") is True else UNKNOWN,
    ]
    state_input = {
        "proposal_id": case["proposal_id"],
        "property": case["property"],
        "prefix": [
            {"step": step["step"], "transaction_hash": step.get("transaction_hash") or step["evidence"].get("event", {}).get("transaction_hash"),
             "status": step.get("status"), "evidence": step["evidence"]}
            for step in steps
        ],
    }
    state_hash = digest(state_input)
    terminal_owner = post.get("after")
    terminal = PASS if same(terminal_owner, expected_after) else UNKNOWN
    output = {
        "status": "complete",
        "tool": "Independent Proposal 29 terminal projection",
        "implementation": "terminal-only predicate over the same saved three-boundary prefix; no BTG oracle import",
        "property": state_input["property"],
        "proposal_id": case["proposal_id"],
        "prefix_order": [step["step"] for step in steps],
        "transaction_hashes": [item["transaction_hash"] for item in state_input["prefix"]],
        "state_input_sha256": state_hash,
        "btg_prefix_decisions": btg,
        "terminal_check": {"observed_boundary": 3, "owner": terminal_owner, "expected_owner": expected_after, "decision": terminal},
        "comparison": {"same_history": True, "same_property": True, "btg_violation_prefix": 2,
                       "terminal_result": terminal, "btg_prefix_result": btg,
                       "terminal_misses_prefix_violation": btg[1] == VIOLATION and terminal == PASS},
        "permission_consequence": case["steps"][3]["evidence"],
        "input_sha256": digest(state_input),
        "runner_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(output, indent=2) + "\n", encoding="utf-8")
    rows = [
        r"% Generated by experiments/run_proposal29_terminal_prefix_check.py.",
        r"\begin{table}[t]\centering\scriptsize",
        r"\caption{Real Proposal 29 prefix counterexample. The same published owner-repair property and the same three-boundary history are supplied to BTG and a terminal-only projection. BTG observes the pre-repair permission boundary and reports VIOLATION; the terminal projection observes only the repaired final owner and reports PASS. The later Proposal 94 call is retained as the permission consequence.}",
        r"\label{tab:proposal29-terminal-prefix}",
        r"\begin{tabular}{@{}p{0.28\linewidth}p{0.27\linewidth}cc@{}}\toprule",
        r"Boundary & Evidence & BTG & Terminal \\\midrule",
        r"L1 repair dispatch & successful proposal-29 dispatch receipt & PASS & -- \\",
        r"Arbitrum pre-repair & owner = unaliased L1 Timelock & VIOLATION & -- \\",
        r"Arbitrum post-repair & OwnerChanged: unaliased $\rightarrow$ aliased owner & PASS & PASS (final) \\",
        r"\bottomrule\end{tabular}",
        r"\end{table}",
    ]
    TABLE.write_text("\n".join(rows) + "\n", encoding="utf-8")
    assert output["comparison"]["terminal_misses_prefix_violation"]
    assert output["btg_prefix_decisions"] == [PASS, VIOLATION, PASS]
    print(json.dumps({"status": output["status"], "btg": btg, "terminal": terminal, "state_input_sha256": state_hash}, indent=2))


if __name__ == "__main__":
    main()
